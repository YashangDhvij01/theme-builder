package com.themebuilder.backend.dto;

import tools.jackson.databind.JsonNode;
import java.time.LocalDateTime;

public class EmailCampaignResponse {

    private Long id;
    private String name;
    private String subject;
    private String previewText;
    private JsonNode sectionsData;
    private String thumbnailUrl;
    private String status;
    private String ownerScope;
    private LocalDateTime createdAt;
    private LocalDateTime updatedAt;

    public EmailCampaignResponse() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSubject() {
        return subject;
    }

    public void setSubject(String subject) {
        this.subject = subject;
    }

    public String getPreviewText() {
        return previewText;
    }

    public void setPreviewText(String previewText) {
        this.previewText = previewText;
    }

    public JsonNode getSectionsData() {
        return sectionsData;
    }

    public void setSectionsData(JsonNode sectionsData) {
        this.sectionsData = sectionsData;
    }

    public String getThumbnailUrl() {
        return thumbnailUrl;
    }

    public void setThumbnailUrl(String thumbnailUrl) {
        this.thumbnailUrl = thumbnailUrl;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getOwnerScope() {
        return ownerScope;
    }

    public void setOwnerScope(String ownerScope) {
        this.ownerScope = ownerScope;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
